#!/usr/bin/env python3
"""mhg_funcnames.py - G addresses for the func_XXXXXX names the shared C uses.

The shared C calls MH1 functions that had no name yet as func_00544C90 (MH1 address). In the G build
those names must point at G's twin of that function. This reads every func_XXXXXX the C uses, finds the
MH1 function at that address in docs/survey/mhg_map.csv and writes PROVIDE lines (linked into every G
module by tools/build.py, read by tools/check.py) to config/mhg/g_funcnames.txt. Functions with a weak
pairing (sim < 0.6) or an address that exists in two overlays are skipped and listed.

Usage: python3 tools/mhg_funcnames.py
"""
import collections
import csv
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "config/mhg/g_funcnames.txt")


def main():
    names = set()
    for p in glob.glob(os.path.join(ROOT, "src/**/*.c"), recursive=True):
        names |= set(re.findall(r"\bfunc_([0-9A-F]{6})\b", open(p, errors="replace").read()))
    rows = collections.defaultdict(list)
    for r in csv.DictReader(open(os.path.join(ROOT, "docs/survey/mhg_map.csv"))):
        if r["mh1_addr"] and r["g_addr"] and r["class"] != "g-only":
            rows[int(r["mh1_addr"], 16)].append(r)
    out, skipped = [], []
    for n in sorted(names):
        a = int(n, 16)
        c = [r for r in rows.get(a, []) if float(r["sim"] or 0) >= 0.6]
        if not c:
            skipped.append((n, "no pair"))
            continue
        ga = {int(r["g_addr"], 16) for r in c}
        if len(ga) > 1:
            skipped.append((n, "ambiguous " + ",".join(sorted(r["mh1_module"] for r in c))))
            continue
        out.append("PROVIDE(func_%s = 0x%08X); /* %s */\n" % (n, ga.pop(), c[0]["name"]))
    with open(OUT, "w") as fh:
        fh.write("/* Generated by tools/mhg_funcnames.py: G addresses of the MH1 address names func_XXXXXX the shared C calls. */\n")
        fh.writelines(out)
    print("%d names, %d skipped" % (len(out), len(skipped)))
    for n, why in skipped:
        print("  skipped func_%s: %s" % (n, why))


if __name__ == "__main__":
    main()
