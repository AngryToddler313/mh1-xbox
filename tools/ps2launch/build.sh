#!/bin/sh
# Build MH1LAUNCH.ELF, the memory-card launcher (src/ps2patch/launcher.c, docs/PLAYING.md), with the open ps2sdk:
#   PS2DEV=~/ps2dev/sdk/ps2dev tools/ps2launch/build.sh        -> build/ps2launch/MH1LAUNCH.ELF
# The ps2sdk toolchain is not in the repo: the prebuilt release from github.com/ps2dev/ps2dev/releases (latest,
# ps2dev-ubuntu-latest.tar.gz) unpacked anywhere; PS2DEV points at its ps2dev/ folder. Needs neither the disc nor the
# PS2 rebuild: the in-game blob (launch_hook.c + online.c) is linked against tools/ps2launch/syms.ld (addresses).
set -e
cd "$(dirname "$0")/../.."
PS2DEV=${PS2DEV:-$HOME/ps2dev/sdk/ps2dev}
PS2SDK=${PS2SDK:-$PS2DEV/ps2sdk}
export PATH="$PS2DEV/ee/bin:$PATH"
CC=mips64r5900el-ps2-elf-gcc
command -v $CC >/dev/null || { echo "no $CC (PS2DEV=$PS2DEV; see the header)"; exit 1; }
O=build/ps2launch; mkdir -p $O

# 1. the in-game blob, linked at 0x268800 (inside the dead ms_net_patch_set) with the game's addresses
cat > $O/mh1p_conf.h <<H
/* the launcher fills server / login / password at run time from MH1LAUNCH.CNF */
#define MH1P_CONF { "MH1SERVER000", "mh1-server", "", "", "", "0", "100" }
H
BF="-O2 -G0 -mno-abicalls -fno-pic -ffreestanding -fno-builtin -nostdlib -fno-common -fno-zero-initialized-in-bss \
    -fno-asynchronous-unwind-tables -Wall -Iinclude -I$O -DMH1_ONLINE_PATCH"
$CC $BF -Dinternet_browser=mh1l_internet_browser -c src/ps2patch/online.c -o $O/online.o
$CC $BF -c src/ps2patch/launch_hook.c -o $O/launch_hook.o
$CC -nostdlib -Wl,--no-warn-mismatch -Wl,-T,tools/ps2launch/blob.ld -Wl,-T,tools/ps2launch/syms.ld \
    -o $O/blob.elf $O/launch_hook.o $O/online.o -Wl,-Map,$O/blob.map -Wl,-e,mh1l_hook
mips64r5900el-ps2-elf-objcopy -O binary -j .blob $O/blob.elf $O/blob.bin
python3 - $O <<'PY'
import subprocess, sys
o = sys.argv[1]
syms = {}
for l in subprocess.check_output(["mips64r5900el-ps2-elf-nm", o + "/blob.elf"], text=True).split("\n"):
    p = l.split()
    if len(p) == 3:
        syms[p[2]] = int(p[0], 16)
b = open(o + "/blob.bin", "rb").read()
assert syms["mh1p_conf"] >= 0x268800 and syms["mh1l_hook"] > 0x268800 and 0x268800 + len(b) <= 0x26A2E8, "blob layout"
with open(o + "/mh1l_blob.h", "w") as f:
    f.write("/* generated by tools/ps2launch/build.sh from launch_hook.c + online.c (our code) */\n")
    f.write("#define MH1L_BLOB_ADDR 0x%Xu\n#define MH1L_CONF_ADDR 0x%Xu\n#define MH1L_HOOK_ADDR 0x%Xu\n"
            % (0x268800, syms["mh1p_conf"], syms["mh1l_hook"]))
    f.write("static const unsigned char mh1l_blob[%d] = {\n" % len(b))
    for i in range(0, len(b), 16):
        f.write("    " + ", ".join("0x%02X" % x for x in b[i:i + 16]) + ",\n")
    f.write("};\n")
print("blob: %d bytes at 0x268800 (room up to 0x26A2E8), conf 0x%X, hook 0x%X, browser 0x%X"
      % (len(b), syms["mh1p_conf"], syms["mh1l_hook"], syms["mh1l_internet_browser"]))
PY

# 2. the launcher, linked high (0x01800000) so that it is not overwritten while it loads the game (0x100000-0xE00000)
sed 's/\.text 0x00100000:/.text 0x01800000:/' $PS2SDK/ee/startup/linkfile > $O/linkfile
grep -q '0x01800000' $O/linkfile || { echo "linkfile: base not found"; exit 1; }
$CC -D_EE -G0 -O2 -Wall -I$PS2SDK/ee/include -I$PS2SDK/common/include -Iinclude -I$O \
    -T$O/linkfile -o $O/MH1LAUNCH.ELF src/ps2patch/launcher.c -L$PS2SDK/ee/lib -Wl,-zmax-page-size=128 \
    -lpatches -ldebug -lcdvd
mips64r5900el-ps2-elf-strip $O/MH1LAUNCH.ELF
ls -l $O/MH1LAUNCH.ELF
